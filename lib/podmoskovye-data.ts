export function cityTravelNote(city: string, region: string) {
  if (region !== PODMOSKOVYE_NAME && region !== LEGACY_REGION_NAME) return null;
  const guide = podmoskovyeCityGuide[city.trim() as keyof typeof podmoskovyeCityGuide];
  if (!guide) return null;
  return `около ${guide.km} км от Москвы · ${guide.days}`;
}

